CREATE TABLE IF NOT EXISTS usuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    usuario VARCHAR(80) NOT NULL,
    password VARCHAR(255) NOT NULL,
    rol VARCHAR(20) NOT NULL,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    PRIMARY KEY (id)
);

CREATE TABLE IF NOT EXISTS cajas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    fecha_apertura TIMESTAMP NOT NULL,
    fecha_cierre TIMESTAMP,
    monto_inicial NUMERIC(12,2) NOT NULL,
    efectivo_contado NUMERIC(12,2),
    observaciones VARCHAR(500),
    estado VARCHAR(10) NOT NULL,
    abierta_por_id BIGINT NOT NULL,
    cerrada_por_id BIGINT,
    PRIMARY KEY (id)
);

CREATE TABLE IF NOT EXISTS carrito (
    idcarrito INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    creado_en TIMESTAMP NOT NULL,
    actualizado_en TIMESTAMP NOT NULL,
    usuario_id BIGINT NOT NULL,
    PRIMARY KEY (idcarrito)
);

CREATE TABLE IF NOT EXISTS clientes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    usuario_id BIGINT NOT NULL,
    nombre VARCHAR(120) NOT NULL,
    correo VARCHAR(160) NOT NULL,
    telefono VARCHAR(30) NOT NULL,
    fecha_nacimiento DATE NOT NULL,
    numero_documento VARCHAR(40),
    foto_url VARCHAR(350),
    fecha_alta DATE NOT NULL,
    PRIMARY KEY (id)
);

CREATE TABLE IF NOT EXISTS productos_bar (
    idproductos_bar INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    nombre VARCHAR(100) NOT NULL,
    descripcion VARCHAR(255),
    precio NUMERIC(10,2) NOT NULL,
    stock INTEGER NOT NULL,
    imagen_url VARCHAR(500),
    creado_en TIMESTAMP NOT NULL,
    idcategorias_bar INTEGER NOT NULL,
