CREATE TABLE IF NOT EXISTS categorias_bar (
    idcategorias_bar INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    nombre VARCHAR(60) NOT NULL,
    descripcion VARCHAR(255),
    PRIMARY KEY (idcategorias_bar)
);

CREATE TABLE IF NOT EXISTS configuracion_gimnasio (
    id BIGINT NOT NULL,
    nombre_comercial VARCHAR(150),
    correo_contacto VARCHAR(255),
    descripcion VARCHAR(2000),
    direccion VARCHAR(255),
    logo_url VARCHAR(255),
    portada_url VARCHAR(255),
    color_primario VARCHAR(255),
    color_secundario VARCHAR(255),
    PRIMARY KEY (id)
);

CREATE TABLE IF NOT EXISTS horarios_atencion (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    dia_semana INTEGER NOT NULL,
    apertura TIME,
    cierre TIME,
    cerrado BOOLEAN NOT NULL DEFAULT FALSE,
    PRIMARY KEY (id)
);

CREATE TABLE IF NOT EXISTS metodos_pago (
    idmetodos_pago INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    nombre VARCHAR(45) NOT NULL,
    PRIMARY KEY (idmetodos_pago)
);

CREATE TABLE IF NOT EXISTS permisos (
    idpermisos INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    descripcion VARCHAR(255) NOT NULL,
