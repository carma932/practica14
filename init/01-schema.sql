);

CREATE TABLE IF NOT EXISTS rutinas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    cliente_id BIGINT NOT NULL,
    creada_por_id BIGINT NOT NULL,
    nombre VARCHAR(120) NOT NULL,
    contenido VARCHAR(255) NOT NULL,
