    fecha_fin TIMESTAMP,
    creado_en TIMESTAMP NOT NULL,
    plan_id BIGINT NOT NULL,
    PRIMARY KEY (idpromocion_IA)
);

CREATE TABLE IF NOT EXISTS promociones (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    nombre VARCHAR(100) NOT NULL,
    tipo VARCHAR(20) NOT NULL,
    valor NUMERIC(10,2) NOT NULL,
    fecha_inicio DATE NOT NULL,
    fecha_fin DATE NOT NULL,
    plan_id BIGINT,
    imagen_url VARCHAR(500),
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    PRIMARY KEY (id)
);

CREATE TABLE IF NOT EXISTS roles_permisos (
    idroles INTEGER NOT NULL,
    idpermisos INTEGER NOT NULL,
    PRIMARY KEY (idroles, idpermisos)
);

CREATE TABLE IF NOT EXISTS asistencias (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    cliente_id BIGINT NOT NULL,
    registrada_por_id BIGINT NOT NULL,
    fecha DATE NOT NULL,
    hora_entrada TIMESTAMP NOT NULL,
    PRIMARY KEY (id)
);

CREATE TABLE IF NOT EXISTS carrito_items (
    idcarrito_items INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    cantidad INTEGER NOT NULL,
    precio_unitario NUMERIC(10,2) NOT NULL,
