);

CREATE TABLE IF NOT EXISTS promocion_ia (
    idpromocion_IA INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    titulo VARCHAR(100) NOT NULL,
    texto_publicictario VARCHAR(255),
    imagen_promt VARCHAR(255),
    imagen_url VARCHAR(500),
    descuento_porcentaje NUMERIC(5,2),
